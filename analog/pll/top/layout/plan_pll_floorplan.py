#!/usr/bin/env python3
"""True 1:1 SKY130 PDK-Scale Floorplan Blueprint for `pll_clock_frontend_r6q_pdk` & `pll_core_r6k4q_pdk`.

Reads selected PDK sub-block bounding boxes and ports and renders a geometric
draft (`pll_r6k4q_floorplan_plan.png`) before any top-level routing. Dimensions
and input hashes come from the actual cells; this is not macro signoff:
  - Quiet Supply Island (`vdd_q` + quiet `vss`): `Xvco` (`pll_vco_ring4_r6_pdk`),
    `Xbuf0..3` (`pll_buffer_r6_pdk`), `Xcp` (`pll_cp_steer_pdk`),
    `Xlf` (`pll_loop_filter_k4_pdk`), and `Xtail` (`serdes_pll_bias_lowpass_slow_r4_pdk`).
  - Host Supply Island (`vdd` + independent host `vss`): `Xpre0` (`pll_cml_prescaler8_pdk`
    with `/2` stage directly above `Xbuf0`), `Xdum1..3` (`pll_frontend_dummy_load_pdk`
    adjacent to `Xbuf1..3`), `Xfb0` (`serdes_cml_to_cmos_pvt_candidate_pdk` below `d08p/n`),
    and `Xpfd` (`pll_pfd_sc_dly_pdk` on outer left feeding `Xcp.up/dn`, >175 um from VCO phases).
"""
from __future__ import annotations

import json
import hashlib
from pathlib import Path
import sys

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import FancyArrowPatch, Rectangle

REPO = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(REPO / "verification/layout"))
from geometry import Cell  # noqa: E402

CELL_PATHS = {
    "vco": REPO / "analog/pll/vco/layout/variants/r6_pdk/pll_vco_ring4_r6_pdk.mag",
    "buf": REPO / "analog/pll/vco/layout/variants/r6_pdk/pll_buffer_r6_pdk.mag",
    "dum": REPO / "analog/pll/divider/layout/variants/pdk/pll_frontend_dummy_load_pdk.mag",
    "pre": REPO / "analog/pll/divider/layout/variants/pdk/pll_cml_prescaler8_pdk.mag",
    "fb": REPO / "analog/common/cml_to_cmos/layout/variants/pdk/serdes_cml_to_cmos_pvt_candidate_pdk.mag",
    "pfd": REPO / "analog/pll/pfd/layout/variants/pdk/pll_pfd_sc_dly_pdk.mag",
    "cp": REPO / "analog/pll/cp/layout/variants/pdk/pll_cp_steer_pdk.mag",
    "lf": REPO / "analog/pll/loop_filter/layout/variants/fused_pdk/pll_loop_filter_k4_fused_pdk.mag",
    "tail": REPO / "analog/common/ldo/layout/variants/smallcap_pdk/serdes_pll_bias_lowpass_slow_r4_pdk.mag",
}

# Geometric draft only; no current routed PLL macro is generated by this table.
PLACEMENTS = [
    # Quiet domain (vdd_q)
    dict(inst="Xvco", kind="vco", domain="quiet", dx=0.00, dy=0.00, mx=False, my=False,
         title="Xvco\npll_vco_ring4_r6_pdk\n(211.2 × 130.7 µm | 248 MIM)"),
    dict(inst="Xbuf0", kind="buf", domain="quiet", dx=-30.55, dy=84.00, mx=False, my=False,
         title="Xbuf0\n(b0)"),
    dict(inst="Xbuf1", kind="buf", domain="quiet", dx=+30.55, dy=84.00, mx=False, my=False,
         title="Xbuf1\n(b1)"),
    dict(inst="Xbuf2", kind="buf", domain="quiet", dx=+30.55, dy=-84.00, mx=False, my=True,
         title="Xbuf2\n(b2)"),
    dict(inst="Xbuf3", kind="buf", domain="quiet", dx=-30.55, dy=-84.00, mx=False, my=True,
         title="Xbuf3\n(b3)"),
    dict(inst="Xtail", kind="tail", domain="quiet", dx=-176.00, dy=84.00, mx=False, my=False,
         title="Xtail\n1MΩ + 16pF Slow Bias LPF\n(100.2 × 103.2 µm)"),
    dict(inst="Xcp", kind="cp", domain="quiet", dx=-242.00, dy=-10.00, mx=False, my=False,
         title="Xcp: pll_cp_steer_pdk (k=4, 200µA)\n(127.6 × 40.6 µm | Cdum=0.3pF)"),
    dict(inst="Xlf", kind="lf", domain="quiet", dx=-172.00, dy=-64.00, mx=False, my=False,
         title="Xlf: pll_loop_filter_k4_fused_pdk\n(98.3 × 70.1 µm | 6 Stacked MIM1+2 + Guard Rings)"),
    # Host domain (vdd)
    dict(inst="Xdum1", kind="dum", domain="host", dx=+66.00, dy=76.00, mx=False, my=False,
         title="Xdum1\n(b1 load)"),
    dict(inst="Xdum2", kind="dum", domain="host", dx=+66.00, dy=-76.00, mx=False, my=True,
         title="Xdum2\n(b2 load)"),
    dict(inst="Xdum3", kind="dum", domain="host", dx=-66.00, dy=-76.00, mx=False, my=True,
         title="Xdum3\n(b3 load)"),
    dict(inst="Xpre0", kind="pre", domain="host", dx=-30.55, dy=128.00, mx=False, my=False,
         title="Xpre0: pll_cml_prescaler8_pdk (/2 h40 → buf → /4 h80 → buf → /8 h80)\n(370.7 × 64.2 µm | /2 input directly over Xbuf0)"),
    dict(inst="Xfb0", kind="fb", domain="host", dx=+278.00, dy=52.00, mx=True, my=False,
         title="Xfb0: CML→CMOS Feedback Rx\n(134.9 × 71.0 µm | d08→fb0)"),
    dict(inst="Xpfd", kind="pfd", domain="host", dx=-276.00, dy=-4.00, mx=False, my=False,
         title="Xpfd\nSC PFD\n(25.3×5.9u)"),
]


def xform_bbox(b: tuple[float, float, float, float], dx: float, dy: float, mx: bool, my: bool):
    x1, y1, x2, y2 = b
    if mx:
        x1, x2 = -x2, -x1
    if my:
        y1, y2 = -y2, -y1
    return [round(x1 + dx, 3), round(y1 + dy, 3), round(x2 + dx, 3), round(y2 + dy, 3)]


def xform_pt(pt: tuple[float, float], dx: float, dy: float, mx: bool, my: bool):
    x, y = pt
    if mx:
        x = -x
    if my:
        y = -y
    return (round(x + dx, 3), round(y + dy, 3))


def main() -> None:
    cells = {k: Cell.read(p) for k, p in CELL_PATHS.items()}
    placed = {}
    for item in PLACEMENTS:
        c = cells[item["kind"]]
        bb = xform_bbox(c.bbox(), item["dx"], item["dy"], item["mx"], item["my"])
        pins = {}
        for _, px, py, nm in c.labels:
            pins[nm] = xform_pt((px, py), item["dx"], item["dy"], item["mx"], item["my"])
        path=CELL_PATHS[item["kind"]]
        width,height=bb[2]-bb[0],bb[3]-bb[1]
        title=item["title"].split("\n")[0]+f"\n{width:.2f} × {height:.2f} µm"
        placed[item["inst"]] = {**item, "title":title,"bbox": bb, "pins": pins,
            "source":str(path.relative_to(REPO)),"sha256":hashlib.sha256(path.read_bytes()).hexdigest()}

    # Check pairwise non-overlap of all 14 sub-blocks!
    names = list(placed)
    for i in range(len(names)):
        for j in range(i + 1, len(names)):
            a, b = placed[names[i]]["bbox"], placed[names[j]]["bbox"]
            ox = min(a[2], b[2]) - max(a[0], b[0])
            oy = min(a[3], b[3]) - max(a[1], b[1])
            if ox > -1.0 and oy > -1.0:
                raise RuntimeError(f"Sub-block overlap/tight clearance ({ox:.2f}, {oy:.2f}) between {names[i]} and {names[j]}")

    fig, (ax_core, ax_fe) = plt.subplots(1, 2, figsize=(21.0, 10.8), dpi=165,
                                         gridspec_kw={"width_ratios": [1.32, 1.0]})

    for ax, mode in ((ax_core, "core"), (ax_fe, "frontend")):
        # Domain background envelopes
        if mode == "core":
            # Quiet supply domain background
            ax.add_patch(Rectangle((-248, -104), 360, 252, fc="#ecfdf5", ec="#059669",
                                   lw=1.4, ls="--", alpha=0.55, zorder=1))
            ax.text(-244, 145, "QUIET SUPPLY DOMAIN (return routing pending)", fontsize=8.0,
                    fontweight="bold", color="#065f46", va="top")
            # Host supply domain background
            ax.add_patch(Rectangle((-92, 109), 382, 74, fc="#eff6ff", ec="#2563eb",
                                   lw=1.4, ls="--", alpha=0.55, zorder=1))
            ax.add_patch(Rectangle((142, 14), 148, 95, fc="#eff6ff", ec="#2563eb",
                                   lw=1.4, ls="--", alpha=0.55, zorder=1))
            ax.text(286, 179, "HOST SUPPLY DOMAIN (shared schematic VSS)", fontsize=8.0,
                    fontweight="bold", color="#1d4ed8", ha="right", va="top")
        else:
            ax.add_patch(Rectangle((-110, -106), 220, 210, fc="#ecfdf5", ec="#059669",
                                   lw=1.3, ls="--", alpha=0.55, zorder=1))

        for inst, info in placed.items():
            if mode == "frontend" and inst in ("Xtail", "Xpfd", "Xcp", "Xlf"):
                continue
            x1, y1, x2, y2 = info["bbox"]
            is_q = info["domain"] == "quiet"
            fc = "#a7f3d0" if (inst == "Xvco") else ("#d1fae5" if is_q else "#dbeafe")
            ec = "#047857" if is_q else "#1d4ed8"
            ax.add_patch(Rectangle((x1, y1), x2 - x1, y2 - y1, fc=fc, ec=ec, lw=1.5, alpha=0.88, zorder=4))

            # Draw internal MIM overlays inside Xvco, Xlf, Xtail, Xcp for true silicon fidelity
            c = cells[info["kind"]]
            for mrect in c.rects.get("mimcap", []):
                mb = xform_bbox(mrect, info["dx"], info["dy"], info["mx"], info["my"])
                ax.add_patch(Rectangle((mb[0], mb[1]), mb[2] - mb[0], mb[3] - mb[1],
                                       fc="#fbbf24", ec="#b45309", lw=0.4, alpha=0.35, hatch="//", zorder=5))

            fs = 6.2 if (x2 - x1) < 35 else 7.2
            ax.text((x1 + x2) / 2, (y1 + y2) / 2, info["title"], ha="center", va="center",
                    fontsize=fs, fontweight="bold", color="#111827", zorder=8,
                    bbox=dict(boxstyle="round,pad=0.15", fc="white", ec=ec, lw=0.6, alpha=0.84))

        # Draw key critical signal vectors
        def arrow(p1, p2, color, lbl=None, rad=0.0):
            ax.add_patch(FancyArrowPatch(p1, p2, arrowstyle="-|>", mutation_scale=10,
                                         lw=1.6, color=color,
                                         connectionstyle=f"arc3,rad={rad}", zorder=10))
            if lbl:
                mx_p, my_p = (p1[0] + p2[0]) / 2, (p1[1] + p2[1]) / 2
                ax.text(mx_p, my_p, lbl, fontsize=6.4, fontweight="bold", color=color,
                        ha="center", va="center", zorder=11,
                        bbox=dict(boxstyle="round,pad=0.1", fc="white", ec=color, lw=0.5, alpha=0.9))

        # Phase -> buffer arrows (13.8 um!)
        for qid, binst in (("0", "Xbuf0"), ("1", "Xbuf1"), ("2", "Xbuf2"), ("3", "Xbuf3")):
            arrow(placed["Xvco"]["pins"][f"q{qid}p"], placed[binst]["pins"]["inp"], "#dc2626", f"q{qid} (14µm)")
        # b0 -> Xpre0
        arrow(placed["Xbuf0"]["pins"]["outp"], placed["Xpre0"]["pins"]["clkp"], "#7c3aed", "b0 (2GHz)")
        # b1..3 -> Xdum1..3
        for binst, dinst, tag in (("Xbuf1", "Xdum1", "b1"), ("Xbuf2", "Xdum2", "b2"), ("Xbuf3", "Xdum3", "b3")):
            arrow(placed[binst]["pins"]["outp"], placed[dinst]["pins"]["clkp"], "#7c3aed", tag)
        # Xpre0.q8 -> Xfb0
        arrow(placed["Xpre0"]["pins"]["q8p"], placed["Xfb0"]["pins"]["inp"], "#2563eb", "d08 (250M)")

        if mode == "core":
            arrow(placed["Xpfd"]["pins"]["up"], placed["Xcp"]["pins"]["up"], "#d97706", "up/dn (9µm)")
            arrow(placed["Xcp"]["pins"]["out"], placed["Xlf"]["pins"]["ctrl"], "#059669", "cpo/ctrl")
            arrow(placed["Xlf"]["pins"]["ctrl"], placed["Xvco"]["pins"]["vctrl"], "#059669", "vctrl")
            arrow(placed["Xtail"]["pins"]["filtered"], placed["Xvco"]["pins"]["vbias"], "#0891b2", "vbias_q")
            arrow(placed["Xfb0"]["pins"]["outp"], (-276.0, 184.0), "#2563eb", "fb0 (CMOS outer bus)", rad=0.12)
            arrow((-276.0, 184.0), placed["Xpfd"]["pins"]["fb"], "#2563eb")
            cx1 = min(v["bbox"][0] for v in placed.values())
            cy1 = min(v["bbox"][1] for v in placed.values())
            cx2 = max(v["bbox"][2] for v in placed.values())
            cy2 = max(v["bbox"][3] for v in placed.values())
            cw, ch = cx2 - cx1, cy2 - cy1
            ax.set_xlim(-296, 304)
            ax.set_ylim(-118, 196)
            ax.set_title(f"1. Full Analog Core `pll_core_r6k4q_pdk` Blueprint — {cw:.0f} × {ch:.0f} µm ({cw*ch/1e6:.3f} mm²)\n"
                         "Left Quiet Loop (Xtail + Xcp + Fused 3×2 Xlf) → Center 2×2 VCO + 4 Buffers → Top/Right Host (/8 + Dummy + FB)",
                         fontsize=9.2, fontweight="bold", pad=8)
        else:
            ax.set_xlim(-120, 304)
            ax.set_ylim(-118, 192)
            ax.set_title("2. Clock Frontend Geometric Draft (r6 shared-bank variant)\n"
                         "Pin vectors only; interconnect, return paths and macro RC are not implemented",
                         fontsize=9.2, fontweight="bold", pad=8)

        ax.set_aspect("equal")
        ax.set_xlabel("x (µm)", fontsize=8)
        ax.set_ylabel("y (µm)", fontsize=8)
        ax.grid(True, lw=0.25, alpha=0.4)

    fig.suptitle("SKY130 `pll_core_r6k4q` — Geometric Placement Draft (sub-block identities in JSON; no macro DRC/LVS/PEX)",
                 fontsize=13.0, fontweight="bold", y=0.985)
    plt.tight_layout(rect=[0, 0.01, 1, 0.955])
    out_png = Path(__file__).with_name("pll_r6k4q_floorplan_plan.png")
    fig.savefig(out_png, dpi=165)
    plt.close(fig)

    out_json = Path(__file__).with_name("pll_r6k4q_floorplan_plan.json")
    out_json.write_text(json.dumps(placed, indent=2) + "\n")
    print("Wrote", out_png, "and", out_json)


if __name__ == "__main__":
    main()
