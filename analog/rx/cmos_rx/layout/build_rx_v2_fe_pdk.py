def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--only", nargs="*", help="Optional subset of cells")
    args = ap.parse_args()

    VARIANT_DIR.mkdir(parents=True, exist_ok=True)
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    cache = PdkCache(RESULTS_DIR / "_pdk_cache")

    specs = [
        ("serdes_rx_term_pdk", "serdes_rx_term_pdk",
         lambda: ctle_b.build_rx_term_pdk(cache, add_ports=True),
         ["inp", "inn", "vcm", "vss"], 120),
        ("serdes_rx_ctle_pdk", "serdes_rx_ctle_pdk",
         lambda: ctle_b.build_rx_ctle_pdk(cache, add_ports=True),
         ["inp", "inn", "outp", "outn", "vbias", "vdd", "vss"], 120),
        ("serdes_rx_dt_slicer_pdk", "serdes_rx_dt_slicer",
         lambda: slicer_b.build_rx_dt_slicer_pdk(cache, add_ports=True),
         ["inp", "inn", "clk", "qp", "qn", "vdd", "vss"], 120),
    ]
    if args.only:
        only_set = set(args.only)
        specs = [s for s in specs if s[0] in only_set]

    summary: dict[str, dict] = {}
    for cell_name, src_subckt, builder, watch_nets, timeout_s in specs:
        print(f"\n=== Building & Independently Reviewing {cell_name} (from {src_subckt}) ===", flush=True)
        mag_path = VARIANT_DIR / f"{cell_name}.mag"
        ref_path = VARIANT_DIR / f"{cell_name}_ref.spice"
        png_path = VARIANT_DIR / f"{cell_name}.png"
        review_dir = RESULTS_DIR / "review" / cell_name

        cell, _meta = builder()
        cell.write(mag_path)
        expected_ports = rlc.generate_rx_ref_spice(src_subckt, cell_name, ref_path)
        rev = rlc.run_independent_review(mag_path, ref_path, review_dir, timeout_s=timeout_s)

        chk = _parse_check_log(review_dir / "check.log")
        fp = rlc.count_floating_poly(mag_path)
        mshares = rlc.compute_metal_shares(mag_path)
        lvs_log = review_dir / f"{cell_name}_lvs.log"
        lvs_txt = lvs_log.read_text() if lvs_log.exists() else ""
        lvs_match = "Circuits match uniquely" in lvs_txt
        lvs_prop_err = "Property errors were found" in lvs_txt
        raw_dev_count = sum(1 for ln in ref_path.read_text().splitlines() if ln.startswith("X"))

        w_um = round(rev["size_um"][0], 3)
        h_um = round(rev["size_um"][1], 3)
        area_um2 = round(w_um * h_um, 2)
        ar = round(w_um / max(h_um, 1e-6), 2)

        pcaps = rev.get("parasitics", {}).get("port_caps_fF", {})
        key_caps = {k: pcaps[k] for k in watch_nets if k in pcaps}
        rc_nets = _parse_rcx_net_resistors(review_dir / f"{cell_name}_rcx.spice", watch_nets)
        internal_cpex = (
            slicer_b.extract_slicer_internal_cpex(review_dir / f"{cell_name}_pex.spice")
            if cell_name == "serdes_rx_dt_slicer_pdk"
            else {}
        )

        rlc.render_png_plot_mag(mag_path, png_path)

        entry = {
            "cell": cell_name,
            "source_subckt": src_subckt,
            "mag": str(mag_path.relative_to(rlc.REPO)),
            "ref_spice": str(ref_path.relative_to(rlc.REPO)),
            "png": str(png_path.relative_to(rlc.REPO)),
            "review_dir": str(review_dir.relative_to(rlc.REPO)),
            "pex_spice": str((review_dir / f"{cell_name}_pex.spice").relative_to(rlc.REPO)),
            "rcx_spice": str((review_dir / f"{cell_name}_rcx.spice").relative_to(rlc.REPO)),
            "bbox_um": [round(v, 3) for v in rev["bbox_um"]],
            "width_um": w_um,
            "height_um": h_um,
            "area_um2": area_um2,
            "aspect_ratio": ar,
            "expected_port_count": len(expected_ports),
            "exported_port_count": len(rev["ports"]),
            "exported_ports": rev["ports"],
            "port_count_match": (len(rev["ports"]) == len(expected_ports) and set(rev["ports"]) == set(expected_ports)),
            "physical_passed": rev["physical_passed"],
            "drc_total": chk["drc_total"],
            "floating_poly": fp,
            "lvs_match": lvs_match,
            "lvs_property_errors": lvs_prop_err,
            "rc_devices_preserved": rev.get("rc", {}).get("devices_preserved", False),
            "rc_resistor_count": rev.get("rc", {}).get("resistor_count", 0),
            "rc_resistor_nets": rev.get("rc", {}).get("resistor_nets", []),
            "raw_device_count": raw_dev_count,
            "merged_device_count": chk["merged_device_count"],
            "net_count": chk["net_count"],
            "metal_shares": mshares,
            "key_port_caps_fF": key_caps,
            "internal_cpex_fF": internal_cpex,
            "key_net_rcx_ohm": rc_nets,
        }
        summary[cell_name] = entry

        # Hard signoff assertions
        assert entry["drc_total"] == 0, f"{cell_name}: DRC={entry['drc_total']}"
        assert entry["floating_poly"] == 0, f"{cell_name}: FP={entry['floating_poly']}"
        assert entry["lvs_match"] is True, f"{cell_name}: LVS mismatch"
        assert entry["lvs_property_errors"] is False, f"{cell_name}: LVS property errors"
        assert entry["port_count_match"] is True, f"{cell_name}: port count mismatch"
        assert entry["physical_passed"] is True, f"{cell_name}: review_cell physical_passed=False"
        assert entry["rc_devices_preserved"] is True, f"{cell_name}: rc.devices_preserved=False"

        print(
            f"  PASS {cell_name}: {w_um:.2f} x {h_um:.2f} um ({area_um2:,.2f} um^2, AR={ar:.2f}) | "
            f"DRC=0 FP=0 LVS=MATCH prop_err=False ports={len(rev['ports'])}/{len(expected_ports)} "
            f"phys=True rc_dev=True devs={raw_dev_count}({chk['merged_device_count']})",
            flush=True,
        )
        print(f"       M1-M5 share: {mshares['share_pct']}", flush=True)
        for kn in ("inp", "inn", "outp", "outn", "clk", "qp", "qn", "vcm"):
            if kn in key_caps:
                print(f"       CPEX {kn:5s}: {key_caps[kn]}", flush=True)
        for kn, kv in internal_cpex.items():
            print(f"       INT  {kn:6s}: {kv}", flush=True)

    if not args.only:
        out_json = VARIANT_DIR / "summary.json"
        out_json.write_text(json.dumps({"variant": "v2_pdk", "pdk": "sky130A", "cells": summary}, indent=2) + "\n")
        _write_readme(summary, VARIANT_DIR / "README.md")
        print(f"\nWrote {out_json} and {VARIANT_DIR / 'README.md'}", flush=True)


if __name__ == "__main__":
    main()
