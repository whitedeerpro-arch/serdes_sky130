"""Retimed TX clock distribution (v2) netlist generator (experimental).

Same ports and name as serdes_cml_clock_distribution_tx_lowov, so the file
drops into the r2 bench via clock_replay --dist.

    divided tap -> PRE gain stages -> d<clk>  --D-->  CML DFF (serdes_cml_dff_lowov)
                                                       ^ clock: node CK of the 2G chain,
                                                       |  optionally inverted, then NCK
                                                       |  dedicated buffers -> k<clk>
                                              r<clk> -> POST stages -> c<clk>
    2G:  spine of buffers from s2g (cfg "chain"); c2g is the output, retimer clocks tap
         spine nodes (v2 default: s2g -> a2g -> e1 -> e2 -> c2g, the v1 chain, no trims)

After retiming every divided clock is "a 2G-chain edge + one clk-to-q", so
the divider delays (which drift ~25-75 ps per stage over PVT) drop out of the
relative timing.  The flip-flop samples on the falling edge of (clkp - clkn).
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[6]
INCLUDES = ("analog/pll/divider/spice/cml_latch.spice", "analog/pll/divider/spice/cml_div2.spice",
            "analog/tx/clock_distribution/spice/tx_clock_retime.spice")

DEFAULT = dict(
    pre={"250": [(20, 12, 400)], "500": [(20, 12, 600), (40, 16, 600)], "1g": [(20, 12, 600), (40, 16, 600)]},
    post={"250": [(64, 64, 100)], "500": [(40, 32, 200)], "1g": [(24, 16, 400)]},
    ck={"250": ("c2g", False, 2), "500": ("e1", False, 1), "1g": ("c2g", False, 1)},
    ckbuf=(24, 16, 400),
    retimer=dict(whold=20),
    # 2G spine: (node, driven from, size).  c2g is the 2G output to the serializer; the
    # retimer clocks tap any spine node.
    chain=(("a2g", "s2g", (20, 12, 400)), ("e1", "a2g", (24, 16, 400)), ("e2", "e1", (24, 16, 400)),
           ("c2g", "e2", (32, 24, 300))),
)
# Named configurations (overrides of DEFAULT).  One CML buffer stage is ~37 ps (0.15 UI) at TT.
PRESETS = {
    "v2": {},
    # v2 left 500M/1G ~0.45 UI early against 250M/2G (serializer-input positions vs the r2
    # calibration).  2G output one stage earlier (driver from e1), 250 retimer one stage earlier,
    # 500/1G retimers two stages later; each move stays inside its retimer's setup/hold window.
    "v2b": dict(
        chain=(("a2g", "s2g", (20, 12, 400)), ("e1", "a2g", (24, 16, 400)), ("c2g", "e1", (32, 24, 300)),
               ("e2", "e1", (24, 16, 400)), ("e3", "e2", (24, 16, 400))),
        ck={"250": ("e3", False, 1), "500": ("e3", False, 1), "1g": ("e3", False, 3)},
    ),
}


def resolve(cfg):
    """Preset name, JSON text or dict -> overrides dict (JSON lists turned back into tuples)."""
    import json
    if isinstance(cfg, str):
        cfg = dict(PRESETS[cfg]) if cfg in PRESETS else json.loads(cfg)
    cfg = dict(cfg or {})
    if "ck" in cfg:
        cfg["ck"] = {k: tuple(v) for k, v in cfg["ck"].items()}
    if "chain" in cfg:
        cfg["chain"] = tuple((n, f, tuple(z)) for n, f, z in cfg["chain"])
    return cfg


def _buf(name, a, b, size):
    wn, wt, r = size
    return f"X{name} {a}p {a}n {b}p {b}n vbias vdd vss serdes_cml_buffer wn={wn} wt={wt} rload={r}"


def netlist(cfg=None):
    cfg = {**DEFAULT, **(cfg or {})}
    rt = " ".join(f"{k}={v}" for k, v in cfg["retimer"].items())
    lines = [f'.include "{ROOT / f}"' for f in INCLUDES]
    lines += ["* Retimed TX clock distribution v2 (generated by variants/dist_v2.py)",
              f"* cfg: {cfg}",
              ".subckt serdes_cml_clock_distribution_tx_lowov s250p s250n s500p s500n s1gp s1gn s2gp s2gn",
              "+ c250p c250n c500p c500n c1gp c1gn c2gp c2gn vbias vdd vss",
              "+ params: trim250=0 trim500=0 trim1g=0 trim2g=0",
              "Xrtbias vbias vbias_rt vdd vss pll_cml_tail_bias"]
    for node, src, size in cfg["chain"]:
        lines.append(_buf(f"ch_{node}", src, node, size))
    for clk in ("250", "500", "1g"):
        # First gain stage output is a<clk> (the bench's pre<clk> probes read it); D input is d<clk>.
        prev = f"s{clk}"
        for i, size in enumerate(cfg["pre"][clk]):
            nxt = f"a{clk}" if i == 0 else (f"d{clk}" if i == len(cfg["pre"][clk]) - 1 else f"pre{clk}_{i}")
            lines.append(_buf(f"pre{clk}_{i}", prev, nxt, size))
            prev = nxt
        if len(cfg["pre"][clk]) == 1:
            lines += [f"Vd{clk}p a{clk}p d{clk}p 0", f"Vd{clk}n a{clk}n d{clk}n 0"]
        node, invert, nck = cfg["ck"][clk]
        src = f"{node}n {node}p" if invert else f"{node}p {node}n"
        ck = node
        for i in range(nck):
            nxt = f"k{clk}" if i == nck - 1 else f"k{clk}_{i}"
            a = src if i == 0 else f"{ck}p {ck}n"
            wn, wt, r = cfg["ckbuf"]
            lines.append(f"Xck{clk}_{i} {a} {nxt}p {nxt}n vbias vdd vss serdes_cml_buffer wn={wn} wt={wt} rload={r}")
            ck = nxt
        kp, kn = (f"{ck}p", f"{ck}n") if nck else ((f"{node}n", f"{node}p") if invert else (f"{node}p", f"{node}n"))
        lines.append(f"Xr{clk} d{clk}p d{clk}n {kp} {kn} r{clk}p r{clk}n vbias vbias_rt vdd vss serdes_cml_dff_lowov {rt}")
        prev = f"r{clk}"
        for i, size in enumerate(cfg["post"][clk]):
            nxt = f"c{clk}" if i == len(cfg["post"][clk]) - 1 else f"post{clk}_{i}"
            lines.append(_buf(f"post{clk}_{i}", prev, nxt, size))
            prev = nxt
    lines.append(".ends serdes_cml_clock_distribution_tx_lowov")
    return "\n".join(lines) + "\n"


def probe_vectors():
    """Internal nodes for setup/hold: retimer D, its internal clock (follower outputs), Q."""
    v = []
    for clk in ("250", "500", "1g"):
        v += [f"v(xclocks.d{clk}p)", f"v(xclocks.d{clk}n)", f"v(xclocks.xr{clk}.ckp)", f"v(xclocks.xr{clk}.ckn)",
              f"v(xclocks.r{clk}p)", f"v(xclocks.r{clk}n)"]
    return v


if __name__ == "__main__":
    import json
    import sys
    # dist_v2.py [out.spice [preset name | json overrides]]: print or write the netlist
    text = netlist(resolve(sys.argv[2] if len(sys.argv) > 2 else {}))
    if len(sys.argv) > 1:
        Path(sys.argv[1]).write_text(text)
    else:
        print(text)
