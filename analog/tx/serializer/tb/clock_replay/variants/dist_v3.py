"""TX clock distribution v3 netlist generator: structure S4 (experimental).

Same ports and name as serdes_cml_clock_distribution_tx_lowov, so the file drops
into the r2 bench via clock_replay --dist.

    s2g -> a2g -> e1 -+-> kc (counter clock driver) -> serdes_tx_sync_counter8 -> q0/q1/q2
                      +-> kr (replica clock driver) -> serdes_cml_clk_replica_lowov -> r2
    q2 -> iso -> O250 -> c250        q1 -> iso -> e500 stages -> O500 -> c500
    q0 -> iso -> e1g stages -> O1g -> c1g        r2 -> iso -> e2g stages -> O2g -> c2g

Every select clock is "one 2 GHz edge + one clk->q (+ equal isolation buffer)";
the e stages centre the rank-to-rank offsets (balance study: e500 = 1, e1g = 2).
The divided PLL taps s250/s500/s1g are not used; they keep the v1 input stage as
a load, so the recorded taps (boundary condition) see the same load.
kc drives the counter's shared followers (3 flip-flops), so it is sized 3x kr
(3x tail and width, R/3) for the same RC.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[6]
INCLUDES = ("analog/pll/divider/spice/cml_latch.spice", "analog/pll/divider/spice/cml_div2.spice",
            "analog/pll/divider/spice/cml_logic.spice", "analog/tx/clock_distribution/spice/tx_clock_retime.spice",
            "analog/tx/clock_distribution/spice/tx_clock_counter.spice")

DEFAULT = dict(
    dummy={"250": (20, 12, 400), "500": (20, 12, 600), "1g": (20, 12, 600)},
    spine=((20, 12, 400), (24, 16, 400)),          # a2g (recorded input stage), e1
    kc=(72, 48, 133), kr=(24, 16, 400),
    iso=(24, 16, 400), stage=(24, 16, 400),
    extra={"250": 0, "500": 2, "1g": 4, "2g": 1},    # centring stages (first probe: 500M/1G/2G early by 0.13/0.24/0.14 UI with 1/2/0)
    out={"250": (64, 64, 100), "500": (40, 32, 200), "1g": (24, 16, 400), "2g": (32, 24, 300)},
    invert={"250": False, "500": False, "1g": False, "2g": False},
    tie=(4, 4, 2000),
    # bench-only start state (stands in for a synchronous reset): every bit low at t = 0, so
    # runs of different length start the counter identically; None leaves it to the solver
    reset_ic="xclocks",
)
PRESETS = {"v3": {}}


def resolve(cfg):
    import json
    if isinstance(cfg, str):
        cfg = dict(PRESETS[cfg]) if cfg in PRESETS else json.loads(cfg)
    return dict(cfg or {})


def _buf(name, a, b, size, invert=False):
    wn, wt, r = size
    o = f"{b}n {b}p" if invert else f"{b}p {b}n"
    return f"X{name} {a}p {a}n {o} vbias vdd vss serdes_cml_buffer wn={wn} wt={wt} rload={r}"


def netlist(cfg=None):
    cfg = {**DEFAULT, **(cfg or {})}
    L = [f'.include "{ROOT / f}"' for f in INCLUDES]
    L += ["* TX clock distribution v3 (S4: synchronous counter + 2G clk->q replica), generated by variants/dist_v3.py",
          f"* cfg: {cfg}",
          ".subckt serdes_cml_clock_distribution_tx_lowov s250p s250n s500p s500n s1gp s1gn s2gp s2gn",
          "+ c250p c250n c500p c500n c1gp c1gn c2gp c2gn vbias vdd vss",
          "+ params: trim250=0 trim500=0 trim1g=0 trim2g=0",
          "Xrtbias vbias vbias_rt vdd vss pll_cml_tail_bias"]
    for clk, size in cfg["dummy"].items():                  # unused divided taps: recorded input load only
        L.append(_buf(f"pre{clk}_0", f"s{clk}", f"a{clk}", size))
    L.append(_buf("ch_a2g", "s2g", "a2g", cfg["spine"][0]))
    L.append(_buf("ch_e1", "a2g", "e1", cfg["spine"][1]))
    L.append(_buf("kc", "e1", "kc", cfg["kc"]))
    L.append(_buf("kr", "e1", "kr", cfg["kr"]))
    wn, wt, r = cfg["tie"]                                   # static CML high/low for the replica
    L.append(f"Xtie vdd vss hip hin vbias vdd vss serdes_cml_buffer wn={wn} wt={wt} rload={r}")
    L.append("Xcnt kcp kcn q0p q0n q1p q1n q2p q2n vbias vbias_rt vdd vss serdes_tx_sync_counter8")
    L.append("Xrep krp krn r2gp r2gn hip hin vbias vbias_rt vdd vss serdes_cml_clk_replica_lowov")
    src = {"250": "q2", "500": "q1", "1g": "q0", "2g": "r2g"}
    for clk in ("250", "500", "1g", "2g"):
        L.append(_buf(f"iso{clk}", src[clk], f"i{clk}", cfg["iso"]))
        prev = f"i{clk}"
        for k in range(cfg["extra"][clk]):
            L.append(_buf(f"e{clk}_{k}", prev, f"e{clk}_{k}", cfg["stage"]))
            prev = f"e{clk}_{k}"
        L.append(_buf(f"out{clk}", prev, f"c{clk}", cfg["out"][clk], cfg["invert"][clk]))
    L.append(".ends serdes_cml_clock_distribution_tx_lowov")
    if cfg["reset_ic"]:
        x = cfg["reset_ic"]
        L.append(".ic " + " ".join(f"v({x}.q{i}p)=1.3 v({x}.q{i}n)=1.6" for i in range(3)))
    return "\n".join(L) + "\n"


def probe_vectors():
    v = [f"v(xclocks.{n})" for n in ("q0p", "q0n", "q1p", "q1n", "q2p", "q2n")]
    v += [f"v(xclocks.xcnt.{n})" for n in ("ckp", "ckn",
                                           "d1p", "d1n", "d2p", "d2n", "m1p", "m1n", "m2p", "m2n")]
    return v + ["v(xclocks.kcp)", "v(xclocks.kcn)", "v(xclocks.krp)", "v(xclocks.krn)",
                "v(xclocks.r2gp)", "v(xclocks.r2gn)"]


if __name__ == "__main__":
    import sys
    text = netlist(resolve(sys.argv[2] if len(sys.argv) > 2 else {}))
    if len(sys.argv) > 1:
        Path(sys.argv[1]).write_text(text)
    else:
        print(text)
