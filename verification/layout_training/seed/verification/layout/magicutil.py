"""Drive Magic headless for the SKY130 layout work.

The layout is generated by scripts, not by hand: each device is drawn by the
PDK's own generator (``sky130::*_draw``) into its own cell, instantiated in the
block cell at explicit coordinates, and routed with painted metal.  That keeps
LVS device recognition in the hands of the PDK and the placement in the hands
of this file.

Only the helpers needed so far live here; block builders sit next to their
module (``analog/<module>/layout/build_<cell>.py`` calls into this module).
"""

from __future__ import annotations

import re
import subprocess
from dataclasses import dataclass
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
PDK = Path("/home/host/.volare/sky130A")
RCFILE = PDK / "libs.tech/magic/sky130A.magicrc"
MAGIC = "magic"
NGC = Path.home() / ".local/eda/netgen/usr/lib/netgen"
NETGENEXEC = NGC / "tcl/netgenexec"
NETGEN_TCL = NGC / "tcl/netgen.tcl"
NETGEN_SETUP = PDK / "libs.tech/netgen/sky130A_setup.tcl"

EMPTY_MAG = """magic
tech sky130A
magscale 1 2
timestamp 0
<< checkpaint >>
<< labels >>
<< properties >>
<< end >>
"""


def new_cell(path: Path) -> None:
    """Create an empty .mag so that Magic can ``load`` it by name."""
    path.write_text(EMPTY_MAG)


@dataclass
class MagicResult:
    log: str
    ok: bool

    def need(self, what: str) -> None:
        if not self.ok:
            raise RuntimeError(f"magic failed ({what}):\n{self.log[-4000:]}")


def run_magic(script: Path, cwd: Path) -> MagicResult:
    """Run a Tcl script with Magic in batch mode (no Tk, no display)."""
    proc = subprocess.run(
        [MAGIC, "-dnull", "-noconsole", "-rcfile", str(RCFILE), str(script)],
        cwd=cwd,
        capture_output=True,
        text=True,
        timeout=1800,
    )
    log = proc.stdout + proc.stderr
    # magic's squashfs wrapper prints a version_check warning to a pipe that may
    # already be closed in batch mode; it is unrelated to the script we run.
    clean = "\n".join(
        l for l in log.splitlines()
        if "tk_version" not in l and "version_check.tcl" not in l
    )
    bad = re.search(r"Error parsing|no such|No such cell", clean)
    return MagicResult(log=log, ok=(proc.returncode == 0 and bad is None))


def um(x: float) -> str:
    return f"{x:.4f}um"


def netgen(layout: Path, top: str, ref: Path, out_log: Path, cwd: Path) -> subprocess.CompletedProcess:
    """Run netgen LVS.

    The packaged netgen here was installed under ~/.local/eda but its startup
    script still loads /usr/lib/netgen/tcl/tclnetgen.so and netgenexec never
    sources it, so ``netgen -batch`` exits silently.  We source a copy with the
    library path fixed; see docs/layout/first_batch.md.
    """
    shim = cwd / "_netgen_local.tcl"
    text = NETGEN_TCL.read_text().replace(
        "load /usr/lib/netgen/tcl/tclnetgen.so",
        f"load {NGC}/tcl/tclnetgen.so",
    )
    shim.write_text(text)
    script = cwd / "_netgen_run.tcl"
    script.write_text(
        "set argv [list lvs {%s %s} {%s %s} %s %s]\n"
        "source %s\n" % (layout, top, ref, top, NETGEN_SETUP, out_log, shim)
    )
    return subprocess.run(
        [str(NETGENEXEC), str(script)], cwd=cwd, capture_output=True, text=True, timeout=1800
    )
